ITEM_IDS: frozenset[str] = frozenset(it.id for it in ITEMS)


def items_for(dim: str) -> tuple[Item, ...]:
    out = tuple(it for it in ITEMS if it.dim == dim)
    if not out:
        raise KeyError(dim)
    return out


def version_of(items) -> str:
    blob = "\n".join(f"{it.id}|{it.source}|{it.needs_quote}|{it.harmful}|{it.question}" for it in items)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:8]


ITEMS_VERSION: str = version_of(ITEMS)
