@dataclass(frozen=True)
class Item:
    id: str                     # 全名：P1 / d3.ack（规则表、缓存都用它）
    dim: str                    # "P"（求助者侧）或 d1..d5
    key: str                    # 抽取 JSON 里的短键：P1 / ack
    question: str
    source: str                 # 见 SOURCES
    needs_quote: bool = True    # False = 「完全没有某样东西」类，无原话可引
    harmful: bool = False       # 有害类：引文若整句来自求助者的话 → 不算（总则 1）


@dataclass(frozen=True)
class Signal:
    present: bool
    quote: str = ""
    quote_fail: bool = False    # 模型说「有」但引文核对不过 → present 记 False（监控编造用）


def _p(key: str, question: str, source: str) -> Item:
    return Item(key, "P", key, question, source)


def _a(dim: str, key: str, question: str, *, source: str = "reply",
       needs_quote: bool = True, harmful: bool = False) -> Item:
    return Item(f"{dim}.{key}", dim, key, question, source, needs_quote, harmful)


